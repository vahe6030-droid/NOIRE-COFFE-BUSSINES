  // =========================================================
  // NORMALIZATION
  // =========================================================

  function normalizeText(text) {
    return String(text ?? "")
      .normalize("NFC")
      .replace(/\uFE0F/g, "")
      .replace(/\s+/g, " ")
      .trim();
  }

  // =========================================================
  // GET TRANSLATION
  // =========================================================

  function getTranslation(text, language) {
    const original = String(text ?? "");
    const key = normalizeText(original);
    const lang = String(language || "")
      .trim()
      .toLowerCase();

    if (!key) {
      return original;
    }

    // Russian is the source language.
    if (lang === "ru") {
      return original;
    }

    if (
      !Object.prototype.hasOwnProperty.call(
        translations,
        lang,
      )
    ) {
      return original;
    }

    const match = Object.keys(translations[lang]).find(
      (item) => normalizeText(item) === key,
    );

    return match
      ? translations[lang][match]
      : original;
  }

  // =========================================================
  // HAS TRANSLATION
  // =========================================================

  function hasTranslation(text, language) {
    const key = normalizeText(text);
    const lang = String(language || "")
      .trim()
      .toLowerCase();

    if (!key || !translations[lang]) {
      return false;
    }

    return Object.keys(translations[lang]).some(
      (item) => normalizeText(item) === key,
    );
  }

  // =========================================================
  // PUBLIC API
  // =========================================================

  const translationIndex = new Map();
  for (const dictionary of Object.values(translations))
    for (const key of Object.keys(dictionary))
      if (!translationIndex.has(normalizeText(key))) translationIndex.set(normalizeText(key), key);
  for (const dictionary of Object.values(translations))
    for (const [key, value] of Object.entries(dictionary))
      if (!translationIndex.has(normalizeText(value))) translationIndex.set(normalizeText(value), key);
  function resolveTranslation(text, language) {
    const key = translationIndex.get(normalizeText(text));
    if (!key) return null;
    return language === "ru" ? translations.ru?.[key] ?? key : translations[language]?.[key] ?? null;
  }

  window.NoireTranslations = Object.freeze({
    resolve: resolveTranslation,
    get: getTranslation,
    has: hasTranslation,
    languages: Object.freeze(["ru", "en", "hy"]),
  });
